import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import {
  readPromptDataJson,
  roleDocsPath,
} from "./prompt-data-files.mjs";

export function renderRoleMarkdown(roles) {
  const categories = new Map();

  for (const role of roles) {
    const categoryRoles = categories.get(role.category) ?? [];
    categoryRoles.push(role);
    categories.set(role.category, categoryRoles);
  }

  const sections = [
    "# Digi Tools Prompt Role Library",
    "",
    "> Generated from `src/data/prompt-builder/roles.json`. Do not edit this file by hand.",
    "",
    "This reference groups the Prompt Builder roles by category. Entries marked",
    "as core represent the strongest general-purpose roles in the library.",
    "",
  ];

  for (const [category, categoryRoles] of categories) {
    sections.push(`## ${category}`, "");

    for (const role of categoryRoles) {
      sections.push(
        `### ${role.name}`,
        `**Core:** ${role.core ? "Yes" : "No"}`,
        "",
        "**Description:**",
        role.description,
        "",
        "**Ability:**",
        role.ability.summary,
        "",
        ...role.ability.bullets.map((bullet) => `- ${bullet}`),
        "",
        `**Illustration:** ${role.illustration.src} (${role.illustration.status})`,
        "",
      );
    }
  }

  return `${sections.join("\n").trim()}\n`;
}

async function loadRoles() {
  const catalog = await readPromptDataJson("roles.json");
  return catalog.roles;
}

export async function generateRoleDocs({ check = false } = {}) {
  const expected = renderRoleMarkdown(await loadRoles());

  if (!check) {
    await writeFile(roleDocsPath, expected, "utf8");
    return;
  }

  const current = await readFile(roleDocsPath, "utf8");
  if (current.replace(/\r\n/g, "\n") !== expected) {
    throw new Error(
      "docs/PROMPT_ROLES.md is stale. Run `npm run data:generate`.",
    );
  }
}

const isMain =
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (isMain) {
  generateRoleDocs({ check: process.argv.includes("--check") })
    .then(() => {
      console.log(
        process.argv.includes("--check")
          ? "Prompt role documentation is current."
          : "Generated docs/PROMPT_ROLES.md.",
      );
    })
    .catch((error) => {
      console.error(error.message);
      process.exitCode = 1;
    });
}
